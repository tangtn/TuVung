// Get an illustrative image URL for any word object
export function getWordIllustration(wordObj) {
  if (!wordObj) return TOPIC_IMAGE_POOLS.default[0];
  if (wordObj.image) return wordObj.image;
  const pool =
    TOPIC_IMAGE_POOLS[wordObj.topicId] || TOPIC_IMAGE_POOLS.default;
  const hash = String(wordObj.word || '')
    .split('')
    .reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  return pool[hash % pool.length];
}

// Offline-safe SVG illustration Data URI fallback if an external image fails to load
export function getFallbackSvgDataUri(wordObj) {
  const icon = wordObj?.topicIcon || '📘';
  const wordText = String(wordObj?.word || 'Vocabulary')
    .replace(/[<>&"']/g, '')
    .slice(0, 20);
  const topicText = String(wordObj?.topicName || 'Luyện Từ Visual')
    .replace(/[<>&"']/g, '')
    .slice(0, 28);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="360" viewBox="0 0 600 360">
    <defs>
      <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="#1e3a8a"/>
        <stop offset="50%" stop-color="#312e81"/>
        <stop offset="100%" stop-color="#4c1d95"/>
      </linearGradient>
    </defs>
    <rect width="600" height="360" rx="28" fill="url(#bg)"/>
    <circle cx="510" cy="70" r="110" fill="#ffffff" fill-opacity="0.06"/>
    <circle cx="90" cy="290" r="130" fill="#ffffff" fill-opacity="0.05"/>
    <text x="300" y="145" font-size="76" text-anchor="middle">${icon}</text>
    <text x="300" y="235" font-family="Plus Jakarta Sans, sans-serif" font-size="38" font-weight="800" fill="#ffffff" text-anchor="middle">${wordText}</text>
    <text x="300" y="280" font-family="Plus Jakarta Sans, sans-serif" font-size="18" font-weight="600" fill="#a5b4fc" text-anchor="middle">${topicText}</text>
  </svg>`;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}
